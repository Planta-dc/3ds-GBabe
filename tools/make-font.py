#!/usr/bin/env python3
"""Generate source/ui_font.c: anti-aliased 4-bit glyph atlases (ASCII 32..126).

The UI draws its own text into a 320x240 canvas, so the glyphs are baked into
the binary as coverage bitmaps instead of shipping a font file the 3DS would
have to rasterise at runtime.

    python3 tools/make-font.py [font-dir] [out.c]

The default font dir is /usr/share/fonts/truetype/dejavu (DejaVu Sans, which is
under the permissive Bitstream Vera / DejaVu licence — see
third_party/fonts/DejaVu-LICENSE.txt). Any TrueType font works; the output is a
derived bitmap, so the licence of the font travels with it.

Requires Pillow: python3 -m pip install pillow
"""
import sys
from PIL import Image, ImageDraw, ImageFont

# name, file, pixel size, line-height trim (DejaVu has generous vertical metrics)
FONTS = [
    ("ui_font_small", "DejaVuSans.ttf", 11),
    ("ui_font_body", "DejaVuSans.ttf", 13),
    ("ui_font_bold", "DejaVuSans-Bold.ttf", 13),
    ("ui_font_title", "DejaVuSans-Bold.ttf", 17),
    ("ui_font_big", "DejaVuSans-Bold.ttf", 26),
]

FIRST, LAST = 32, 126


def main() -> int:
    fdir = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu"
    out = sys.argv[2] if len(sys.argv) > 2 else "source/ui_font.c"

    lines = [
        "/*",
        " * Generated by tools/make-font.py from DejaVu Sans. Do not edit.",
        " *",
        " * Glyphs are 4-bit coverage (0 = transparent, 15 = opaque), two per",
        " * byte, for ASCII 32..126. DejaVu Sans is distributed under the",
        " * Bitstream Vera / DejaVu licence: see",
        " * third_party/fonts/DejaVu-LICENSE.txt.",
        " */",
        '#include "ui_gfx.h"',
        "",
    ]

    for name, fname, size in FONTS:
        font = ImageFont.truetype(f"{fdir}/{fname}", size)
        ascent, descent = font.getmetrics()

        glyphs = []
        data = bytearray()

        for code in range(FIRST, LAST + 1):
            ch = chr(code)
            adv = round(font.getlength(ch))
            x0, y0, x1, y1 = font.getbbox(ch)  # from the top of the ascent line
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            off = len(data)
            if w and h:
                img = Image.new("L", (w, h), 0)
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
                nibbles = [min(15, (v + 8) // 17) for v in img.getdata()]
                if len(nibbles) & 1:
                    nibbles.append(0)
                for i in range(0, len(nibbles), 2):
                    data.append(nibbles[i] | (nibbles[i + 1] << 4))
            # getbbox() is relative to the top of the line, and ui_text()
            # takes the top of the line as its origin: same coordinate space.
            glyphs.append((x0, y0, w, h, adv, off))

        lines.append(f"static const unsigned char {name}_bits[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 20):
            lines.append("\t" + ", ".join(f"{b}" for b in data[i:i + 20]) + ",")
        lines.append("};")
        lines.append("")

        lines.append(f"static const ui_glyph {name}_glyphs[{LAST - FIRST + 1}] = {{")
        for (x, y, w, h, adv, off) in glyphs:
            lines.append(f"\t{{ {x}, {y}, {w}, {h}, {adv}, {off} }},")
        lines.append("};")
        lines.append("")

        lines.append(f"const ui_font {name} = {{ {size}, "
                     f"{ascent - 1}, {name}_glyphs, {name}_bits }};")
        lines.append("")

    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
